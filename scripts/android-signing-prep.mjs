import { execFile } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { access, mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { loadLocalEnv } from './lib/env-loader.mjs'

const root = process.cwd()
const localEnv = await loadLocalEnv({ root })
const dataDir = path.join(root, 'data')
const srcDataDir = path.join(root, 'src', 'data')
const reportsDir = path.join(root, 'reports')
const signingDir = path.join(root, 'ops', 'android', 'signing')
const keystorePath = path.join(signingDir, 'release.keystore')
const certificatePath = path.join(signingDir, 'certificate.pem')
const privateKeyPath = path.join(signingDir, 'private-key.pem')
const localEnvRelativePath = 'ops/production.env.local'
const localEnvPath = path.join(root, ...localEnvRelativePath.split('/'))
const outputJsonPath = path.join(dataDir, 'android-signing.json')
const outputTsPath = path.join(srcDataDir, 'androidSigning.ts')
const reportPath = path.join(reportsDir, 'android-signing-latest.md')

const exists = async (filePath) =>
  access(filePath)
    .then(() => true)
    .catch(() => false)

const readOptionalJson = async (filePath, fallback) =>
  readFile(filePath, 'utf8')
    .then((raw) => JSON.parse(raw))
    .catch(() => fallback)

const run = (command, args) =>
  new Promise((resolve) => {
    execFile(command, args, { cwd: root, timeout: 30_000 }, (error, stdout, stderr) => {
      resolve({
        ok: !error,
        stdout: stdout.trimEnd(),
        stderr: stderr.trimEnd(),
      })
    })
  })

const configured = (value) => typeof value === 'string' && value.trim().length > 0
const envFlag = (name) => ['1', 'true', 'yes'].includes(String(process.env[name] ?? '').toLowerCase())
const relative = (filePath) => path.relative(root, filePath)
const quoteEnv = (value) => `"${String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`

const parseEnvFile = (raw) => {
  const result = new Map()

  for (const line of raw.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=(.*)$/)
    if (!match) {
      continue
    }

    result.set(match[1], match[2].trim())
  }

  return result
}

const upsertEnvFile = async (updates) => {
  const existingRaw = await readFile(localEnvPath, 'utf8').catch(() => '')
  const existingKeys = parseEnvFile(existingRaw)
  const lines = existingRaw ? existingRaw.split(/\r?\n/) : []
  const nextLines = []
  const seen = new Set()

  for (const line of lines) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=/)

    if (match && Object.hasOwn(updates, match[1])) {
      nextLines.push(`${match[1]}=${quoteEnv(updates[match[1]])}`)
      seen.add(match[1])
    } else if (line.trim()) {
      nextLines.push(line)
    }
  }

  if (!existingKeys.size) {
    nextLines.push('# Local production values generated by android-signing-prep.')
    nextLines.push('# This file is git-ignored; do not commit secrets.')
  }

  for (const [key, value] of Object.entries(updates)) {
    if (!seen.has(key)) {
      nextLines.push(`${key}=${quoteEnv(value)}`)
    }
  }

  await mkdir(path.dirname(localEnvPath), { recursive: true })
  await writeFile(localEnvPath, `${nextLines.join('\n').replace(/\n+$/, '')}\n`)
}

const extractFingerprint = async ({ filePath, storePass, alias }) => {
  if (!configured(storePass) || !configured(alias) || !(await exists(filePath))) {
    return null
  }

  const result = await run('keytool', ['-list', '-v', '-keystore', filePath, '-storepass', storePass, '-alias', alias])
  const match = result.stdout.match(/SHA256:\s*([A-F0-9:]+)/i)

  return match?.[1]?.toUpperCase() ?? null
}

const extractOpenSslFingerprint = async (filePath) => {
  if (!(await exists(filePath))) {
    return null
  }

  const result = await run('openssl', ['x509', '-in', filePath, '-noout', '-fingerprint', '-sha256'])
  const match = result.stdout.match(/sha256 Fingerprint=([A-F0-9:]+)/i)

  return match?.[1]?.toUpperCase() ?? null
}

const writeKeystoreFromBase64 = async ({ base64Value }) => {
  if (!configured(base64Value)) {
    return false
  }

  await mkdir(signingDir, { recursive: true })
  await writeFile(keystorePath, Buffer.from(base64Value, 'base64'))
  return true
}

const previous = await readOptionalJson(outputJsonPath, {
  signing: {},
  localFiles: {},
})
const ciEnvironment = envFlag('CI') || envFlag('GITHUB_ACTIONS')
const packageName = process.env.AGL_ANDROID_PACKAGE_NAME?.trim() || 'app.autonomousgamelab.portal'
const alias = process.env.AGL_ANDROID_KEY_ALIAS?.trim() || previous.signing?.keyAlias || 'autonomous-game-lab'
let storePass = process.env.AGL_ANDROID_KEYSTORE_PASSWORD?.trim() || null
let keystoreBase64 = process.env.AGL_ANDROID_KEYSTORE_BASE64?.trim() || null
let fingerprint = process.env.AGL_ANDROID_SHA256_CERT_FINGERPRINT?.trim() || previous.signing?.sha256CertFingerprint || null
let generatedThisRun = false
let restoredFromBase64 = false
let keytoolAvailable = (await run('keytool', ['-help'])).ok
let opensslAvailable = (await run('openssl', ['version'])).ok
let keystoreExists = await exists(keystorePath)
let storeType = previous.signing?.storeType ?? 'jks-or-pkcs12'

if (!keystoreExists && configured(keystoreBase64)) {
  restoredFromBase64 = await writeKeystoreFromBase64({ base64Value: keystoreBase64 })
  keystoreExists = await exists(keystorePath)
}

if (!fingerprint && keystoreExists && configured(storePass)) {
  fingerprint = await extractFingerprint({ filePath: keystorePath, storePass, alias })
}

if (!fingerprint && !ciEnvironment && (keytoolAvailable || opensslAvailable)) {
  storePass = randomBytes(24).toString('base64url')
  await mkdir(signingDir, { recursive: true })

  const generateResult = keytoolAvailable
    ? await run('keytool', [
        '-genkeypair',
        '-v',
        '-keystore',
        keystorePath,
        '-storepass',
        storePass,
        '-keypass',
        storePass,
        '-alias',
        alias,
        '-keyalg',
        'RSA',
        '-keysize',
        '2048',
        '-validity',
        '10000',
        '-dname',
        'CN=Autonomous Game Lab, OU=Autonomous Studio, O=Autonomous Game Lab, L=Internet, ST=Online, C=US',
      ])
    : await (async () => {
        const certResult = await run('openssl', [
          'req',
          '-x509',
          '-newkey',
          'rsa:2048',
          '-keyout',
          privateKeyPath,
          '-out',
          certificatePath,
          '-days',
          '10000',
          '-nodes',
          '-subj',
          '/CN=Autonomous Game Lab/OU=Autonomous Studio/O=Autonomous Game Lab/L=Internet/ST=Online/C=US',
        ])

        if (!certResult.ok) {
          return certResult
        }

        return run('openssl', [
          'pkcs12',
          '-export',
          '-inkey',
          privateKeyPath,
          '-in',
          certificatePath,
          '-out',
          keystorePath,
          '-password',
          `pass:${storePass}`,
          '-name',
          alias,
        ])
      })()

  if (generateResult.ok) {
    generatedThisRun = true
    keystoreExists = await exists(keystorePath)
    storeType = keytoolAvailable ? 'jks' : 'pkcs12'
    fingerprint = keytoolAvailable
      ? await extractFingerprint({ filePath: keystorePath, storePass, alias })
      : await extractOpenSslFingerprint(certificatePath)
  }
}

if (keystoreExists && !keystoreBase64) {
  keystoreBase64 = (await readFile(keystorePath)).toString('base64')
}

const localSecretsReady =
  configured(keystoreBase64) &&
  configured(storePass) &&
  configured(alias) &&
  configured(fingerprint) &&
  keystoreExists

if (localSecretsReady) {
  await upsertEnvFile({
    AGL_ANDROID_PACKAGE_NAME: packageName,
    AGL_ANDROID_SHA256_CERT_FINGERPRINT: fingerprint,
    AGL_ANDROID_KEYSTORE_BASE64: keystoreBase64,
    AGL_ANDROID_KEYSTORE_PASSWORD: storePass,
    AGL_ANDROID_KEY_ALIAS: alias,
  })
}

const checks = [
  {
    id: 'signing-tool',
    status: keytoolAvailable || opensslAvailable ? 'pass' : 'blocker',
    detail: keytoolAvailable
      ? 'keytool is available for Android signing material.'
      : opensslAvailable
        ? 'OpenSSL is available for PKCS#12 Android signing material.'
        : 'Neither keytool nor OpenSSL is available.',
  },
  {
    id: 'keystore-file',
    status: keystoreExists ? 'pass' : ciEnvironment ? 'missing-env' : 'blocker',
    detail: keystoreExists
      ? `Local keystore exists at ${relative(keystorePath)}.`
      : 'No local keystore exists; CI will need signing secrets.',
  },
  {
    id: 'fingerprint',
    status: configured(fingerprint) ? 'pass' : 'blocker',
    detail: configured(fingerprint)
      ? 'SHA-256 fingerprint is available for Digital Asset Links.'
      : 'SHA-256 fingerprint is missing.',
  },
  {
    id: 'local-env-sync',
    status: localSecretsReady ? 'pass' : configured(fingerprint) ? 'missing-env' : 'blocker',
    detail: localSecretsReady
      ? `Signing values were synced into ${relative(localEnvPath)} with secret values redacted from reports.`
      : 'Signing env values are not fully available.',
  },
  {
    id: 'secret-redaction',
    status: 'pass',
    detail: 'Keystore bytes, base64, and password are never written to committed reports or src/data artifacts.',
  },
]

const blockers = checks.filter((check) => check.status === 'blocker').map((check) => `${check.id}: ${check.detail}`)
const status = blockers.length
  ? ciEnvironment && configured(fingerprint)
    ? 'signing-fingerprint-known-secrets-needed'
    : 'signing-needs-attention'
  : 'signing-prepared'

const payload = {
  generatedAt: new Date().toISOString(),
  status,
  envFiles: localEnv,
  platform: 'android-trusted-web-activity',
  packageName,
  signing: {
    keyAlias: alias,
    sha256CertFingerprint: fingerprint ?? null,
    fingerprintSource: process.env.AGL_ANDROID_SHA256_CERT_FINGERPRINT
      ? 'environment'
      : generatedThisRun
        ? 'generated-local-keystore'
        : previous.signing?.sha256CertFingerprint
          ? 'previous-signing-evidence'
          : 'missing',
    generatedThisRun,
    restoredFromBase64,
    validityDays: 10000,
    algorithm: 'RSA-2048',
    storeType,
  },
  localFiles: {
    keystorePath: relative(keystorePath),
    certificatePath: relative(certificatePath),
    localEnvPath: relative(localEnvPath),
    keystoreExists,
    localEnvWritten: localSecretsReady,
    gitIgnored: true,
  },
  ciSecrets: {
    required: ['AGL_ANDROID_KEYSTORE_BASE64', 'AGL_ANDROID_KEYSTORE_PASSWORD', 'AGL_ANDROID_KEY_ALIAS'],
    configuredLocally: localSecretsReady,
    valuesRedacted: true,
  },
  controls: {
    zeroPaidSpend: true,
    noAccountCreation: true,
    noStoreSubmission: true,
    noRevenueEnablement: true,
    noSecretValuesInReports: true,
    localSecretFilesGitIgnored: true,
    doesNotCommitKeystore: true,
    doesNotRotateExistingFingerprintInCi: true,
  },
  checks,
  blockers,
  nextActions: [
    localSecretsReady
      ? 'Use production bootstrap to sync AGL_ANDROID_* values into GitHub variables and secrets when a repository token exists.'
      : 'Provide AGL_ANDROID_KEYSTORE_BASE64, AGL_ANDROID_KEYSTORE_PASSWORD, and AGL_ANDROID_KEY_ALIAS in CI before release builds.',
    'Keep Google Play submission blocked until host, privacy, account, and unit-economics gates pass.',
  ],
}

const report = [
  '# Android Signing',
  '',
  `Generated: ${payload.generatedAt}`,
  `Status: ${payload.status}`,
  `Package: ${payload.packageName}`,
  `Fingerprint: ${payload.signing.sha256CertFingerprint ?? 'missing'}`,
  '',
  '## Local Files',
  '',
  `- Keystore: ${payload.localFiles.keystorePath} (${payload.localFiles.keystoreExists ? 'present' : 'missing'})`,
  `- Local env: ${payload.localFiles.localEnvPath} (${payload.localFiles.localEnvWritten ? 'synced' : 'not synced'})`,
  `- Git ignored: ${payload.localFiles.gitIgnored}`,
  '',
  '## Checks',
  '',
  ...payload.checks.map((check) => `- ${check.status}: ${check.id} - ${check.detail}`),
  '',
  '## Guardrails',
  '',
  ...Object.entries(payload.controls).map(([key, value]) => `- ${key}: ${value}`),
  '',
  '## Blockers',
  '',
  ...(payload.blockers.length ? payload.blockers.map((blocker) => `- ${blocker}`) : ['- none']),
  '',
]

await mkdir(path.dirname(outputJsonPath), { recursive: true })
await mkdir(path.dirname(outputTsPath), { recursive: true })
await mkdir(path.dirname(reportPath), { recursive: true })
await writeFile(outputJsonPath, JSON.stringify(payload, null, 2) + '\n')
await writeFile(
  outputTsPath,
  `export const androidSigning = ${JSON.stringify(payload, null, 2)} as const\n\nexport type AndroidSigning = typeof androidSigning\n`,
)
await writeFile(reportPath, report.join('\n'))

console.log(`Wrote ${relative(outputJsonPath)}`)
console.log(`Wrote ${relative(outputTsPath)}`)
console.log(`Wrote ${relative(reportPath)}`)

if (process.argv.includes('--assert-prepared') && payload.status !== 'signing-prepared') {
  console.error('Android signing material is not prepared.')
  process.exit(1)
}
